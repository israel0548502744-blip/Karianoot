"""Writes golden cases for the Kotlin port of hebrew-num2words (HebrewNumbers.kt).

Usage: python tools/numbers_golden.py android/engine/src/test/resources/numbers_golden.json
"""
import json, sys, random
from hebrew_num2words import normalize_numbers

CASES = [
    "היחס הוא 2.5", "יחס של 1.85 על ניצחון", "היחס 3.40 זה מטורף", "ניצחון 3-1 לריאל", "התוצאה 0-0 במחצית",
    "המשחק בשעה 21:45", "בשעה 20:00 נתחיל", "ב-19:30 שריקת הפתיחה", "70% סיכוי", "יש 55.5% שזה ייגמר",
    "2 שערים לפחות", "3 משחקים היום", "8 שעות", "8 שקלים", "שמתי 100 שקלים", "רווח של 1,250 שקלים",
    "2 נקודות", "1 גול", "11 שחקנים", "90 דקות", "45 דקות", "ה-3 בטבלה", "מקום 4", "בפעם 2", "מחזור 12",
    "ב-1.9 יש משחק", "ב-12.5 נשחק", "בתאריך 15.3.2025", "3.2025", "1/2", "3/4", "15/3", "קוד 1234", "054-1234567",
    "1-800-500-600", "1,000,000 צפיות", "2,500,000", "שנת 2024", "בשנת 1998", "בן 25", "כמעט 1000 איש",
    "2 אחוז", "10% אחוז", "יותר מ-5", "עד 3", "007", "12345", "-5 מעלות", "מינוס", "x2.5", "3.14159",
    "19.90 שקלים", "1.05", "0.5", "יחס 1.5 על אובר 2.5 שערים", "ההימור: 3 משחקים, יחס כולל 6.75!",
    "ליגת האלופות 2025/26", "21 ימים", "שלושה ו-4", "1", "2", "10", "11", "20", "21", "99", "100", "101", "110",
    "200", "999", "1001", "2000", "3000", "10000", "11000", "21000", "123456", "999999",
]
random.seed(1)
for _ in range(150):
    n = random.choice([random.randint(0, 99), random.randint(100, 9999), random.randint(10000, 999999)])
    noun = random.choice(["", "שערים", "דקות", "שקלים", "נקודות", "משחקים", "פעמים", "אחוז"])
    CASES.append(f"{n} {noun}".strip())
    CASES.append(f"{random.randint(1,9)}.{random.randint(0,99)}")
out = [{"text": c, "norm": normalize_numbers(c)} for c in CASES]
json.dump(out, open(sys.argv[1], "w"), ensure_ascii=False, indent=0)
print(len(out), "cases")
